export function getGradeVocabulary(gradeLevel, difficulty = null) {
  const vocabGroup = vocabularyByDifficulty[gradeLevel] || vocabularyByDifficulty[1];
  const sentGroup = shortSentencesByDifficulty[gradeLevel] || {};
  const tiers = difficulty ? [difficulty] : ['easy', 'medium', 'hard'];
  const entries = [];
  for (const tier of tiers) {
    const words = (vocabGroup[tier] || '').split(' ').filter(Boolean);
    const sents = sentGroup[tier] || [];
    for (const text of [...words, ...sents]) {
      entries.push({ text, difficultyTier: tier });
    }
  }
  return entries.map(({ text, difficultyTier }) => {
    const bopomofo = Array.from(text).map((character, index) => {
      const candidates = getCharacterReadings(character);
      const reading = wordReadings[text]?.[index] || readings[character] || (candidates.length === 1 ? candidates[0] : null);
      if (!reading || !isDictionaryReading(character, reading)) {
        throw new Error(`自編詞語「${text}」的「${character}」需補上正確語境注音。`);
      }
      return reading;
    });
    return { text, bopomofo, gradeLevel, difficultyTier, sourceKind: 'authored-vocabulary',
      meaning: '遊戲自編分級詞語與生活短句・字音依教育部國語小字典核對。' };
  });
}
